// Writes client/syntaxes/abl.tmLanguage.json: a TextMate grammar that colours
// ABL as soon as a file opens, before the language server's semantic tokens
// arrive (they then refine it). The keywords and types come from the server's
// own table in crates/core/src/keywords.rs, abbreviations included, so the two
// agree. build.ps1 runs it.
//
//   node scripts/grammar.js
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'crates', 'core', 'src', 'keywords.rs'), 'utf8');

function table(name) {
  const m = new RegExp(`const ${name}: &\\[&str\\] = &\\[([\\s\\S]*?)\\];`).exec(src);
  if (!m) throw new Error(`no ${name} table in keywords.rs`);
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// "DEF|INE" -> DEF(?:I(?:N(?:E)?)?)?  : every abbreviation the compiler takes.
function pattern(entry) {
  const [head, rest = ''] = entry.split('|');
  let tail = '';
  for (let i = rest.length - 1; i >= 0; i--) tail = `(?:${esc(rest[i])}${tail})?`;
  return esc(head) + tail;
}

function words(entries) {
  // Longest first, so DEFINE-ish alternatives don't stop at a shorter keyword.
  const pats = [...new Set(entries)].sort((a, b) => b.replace('|', '').length - a.replace('|', '').length).map(pattern);
  // ABL words contain `-`, so a keyword must not touch letters, digits, - or _.
  return `(?i)(?<![\\w-])(?:${pats.join('|')})(?![\\w-])`;
}

const types = table('TYPES');
const keywords = table('KEYWORDS').filter((k) => !types.includes(k));

const PREPROCESSOR =
  'GLOBAL-DEFINE|SCOPED-DEFINE|UNDEFINE|IF|ELSEIF|ELSE|ENDIF|THEN|MESSAGE|ANALYZE-SUSPEND|ANALYZE-RESUME';

const grammar = {
  $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
  name: 'OpenEdge ABL',
  scopeName: 'source.abl',
  comment: 'Generated by scripts/grammar.js from crates/core/src/keywords.rs. Do not edit by hand.',
  patterns: [
    { include: '#comment' },
    { include: '#string' },
    { include: '#preprocessor' },
    { include: '#include' },
    { include: '#annotation' },
    { include: '#number' },
    { include: '#type' },
    { include: '#keyword' },
    { include: '#operator' },
  ],
  repository: {
    comment: {
      patterns: [
        {
          // ABL block comments nest.
          name: 'comment.block.abl',
          begin: '/\\*',
          end: '\\*/',
          patterns: [{ include: '#comment' }],
        },
        { name: 'comment.line.double-slash.abl', match: '//.*$' },
      ],
    },
    string: {
      patterns: [
        {
          name: 'string.quoted.double.abl',
          begin: '"',
          // An optional :U / :T / :R(40) / :L attribute after the closing quote.
          end: '"(?::[RrLlCcTtUu]?\\d*)?',
          patterns: [{ name: 'constant.character.escape.abl', match: '~.' }],
        },
        {
          name: 'string.quoted.single.abl',
          begin: "'",
          end: "'(?::[RrLlCcTtUu]?\\d*)?",
          patterns: [{ name: 'constant.character.escape.abl', match: '~.' }],
        },
      ],
    },
    preprocessor: {
      patterns: [
        {
          // &GLOBAL-DEFINE NAME / &SCOPED-DEFINE NAME / &UNDEFINE NAME: the name too.
          name: 'meta.preprocessor.abl',
          match: '(?i)(&(?:GLOBAL-DEFINE|SCOPED-DEFINE|UNDEFINE))(?![\\w-])(?:\\s+([\\w-]+))?',
          captures: {
            1: { name: 'keyword.control.directive.abl' },
            2: { name: 'entity.name.function.preprocessor.abl' },
          },
        },
        {
          name: 'keyword.control.directive.abl',
          match: `(?i)&(?:${PREPROCESSOR})(?![\\w-])`,
        },
        {
          // {&NAME} and {&NAME}-suffixes
          name: 'variable.other.constant.preprocessor.abl',
          match: '\\{&[\\w-]*\\}',
        },
      ],
    },
    include: {
      // {file.i arg1 &name=value}: an include reference.
      name: 'meta.preprocessor.include.abl',
      begin: '\\{(?![&\\d*])',
      end: '\\}',
      beginCaptures: { 0: { name: 'punctuation.definition.include.begin.abl' } },
      endCaptures: { 0: { name: 'punctuation.definition.include.end.abl' } },
      patterns: [
        { include: '#string' },
        { include: '#preprocessor' },
        { name: 'string.unquoted.include.abl', match: '^[^\\s}]+|(?<=\\{)[^\\s}]+' },
      ],
    },
    annotation: {
      name: 'storage.type.annotation.abl',
      // @Test, @Test (expected=...), @Some.Name: without the statement's period.
      match: '(?i)(?<![\\w-])@[\\w-]+(?:\\.[\\w-]+)*',
    },
    number: {
      name: 'constant.numeric.abl',
      match: '(?<![\\w-])(?:0[xX][0-9a-fA-F]+|\\d+(?:\\.\\d+)?)(?![\\w-])',
    },
    type: {
      name: 'storage.type.abl',
      match: words(types),
    },
    keyword: {
      name: 'keyword.other.abl',
      match: words(keywords),
    },
    operator: {
      patterns: [
        { name: 'keyword.operator.comparison.abl', match: '<>|<=|>=|=|<|>' },
        { name: 'keyword.operator.arithmetic.abl', match: '\\+|(?<![\\w-])-(?![\\w-])|\\*|/' },
      ],
    },
  },
};

const out = path.join(root, 'client', 'syntaxes', 'abl.tmLanguage.json');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(grammar, null, 2) + '\n');
console.log(`Wrote ${path.relative(root, out)}: ${keywords.length} keywords, ${types.length} types`);
