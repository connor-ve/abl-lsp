// Writes client/THIRD-PARTY-NOTICES.txt: the licences of the open-source code
// that ships in abl.exe (Rust crates) and in the VS Code extension (npm
// packages). build.ps1 runs it; release.ps1 puts the file in the zip.
//
//   node scripts/notices.js
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const out = path.join(root, 'client', 'THIRD-PARTY-NOTICES.txt');

const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-._].*)?$/i;

function licenseFiles(dir) {
  let names;
  try {
    names = fs.readdirSync(dir);
  } catch {
    return [];
  }
  return names
    .filter((n) => LICENSE_FILE.test(n) && fs.statSync(path.join(dir, n)).isFile())
    .sort()
    .map((n) => fs.readFileSync(path.join(dir, n), 'utf8').replace(/\r\n/g, '\n').trim());
}

// ---- Rust: the crates abl-cli links, for Windows, without dev-dependencies ----
const meta = JSON.parse(
  execFileSync('cargo', ['metadata', '--format-version', '1', '--filter-platform', 'x86_64-pc-windows-msvc'], {
    cwd: root,
    maxBuffer: 256 * 1024 * 1024,
  }).toString(),
);
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const start = meta.packages.find((p) => p.name === 'abl-cli').id;
const seen = new Set();
const stack = [start];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id).deps) {
    if (d.dep_kinds.some((k) => k.kind === null || k.kind === 'build')) stack.push(d.pkg);
  }
}
const crates = [...seen]
  .map((id) => byId.get(id))
  .filter((p) => p.source) // not our own crates
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
  .map((p) => ({
    name: p.name,
    version: p.version,
    license: p.license || '(see licence text)',
    url: p.repository || `https://crates.io/crates/${p.name}`,
    texts: licenseFiles(path.dirname(p.manifest_path)),
  }));

// ---- npm: what the extension ships (production dependencies) ----
const client = path.join(root, 'client');
const parseable = execFileSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['ls', '--omit=dev', '--all', '--parseable'], {
  cwd: client,
  shell: process.platform === 'win32',
})
  .toString()
  .split(/\r?\n/)
  .filter((l) => l.trim() && path.resolve(l) !== path.resolve(client));
const npm = [...new Set(parseable)]
  .map((dir) => {
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository && pkg.repository.url;
    return {
      name: pkg.name,
      version: pkg.version,
      license: typeof pkg.license === 'string' ? pkg.license : '(see licence text)',
      url: repo || `https://www.npmjs.com/package/${pkg.name}`,
      texts: licenseFiles(dir),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// ---- write: each distinct licence text once, with the packages under it ----
// A crate published without its licence file (like a project's macro crate)
// takes the text of a crate from the same repository.
const all = [...crates, ...npm];
for (const p of all) {
  if (p.texts.length) continue;
  const sibling = all.find((q) => q !== p && q.texts.length && q.url === p.url);
  if (sibling) p.texts = sibling.texts;
}
const groups = new Map();
const missing = [];
for (const p of [...crates, ...npm]) {
  if (!p.texts.length) missing.push(p);
  for (const t of p.texts) {
    if (!groups.has(t)) groups.set(t, []);
    groups.get(t).push(p);
  }
}
const line = '='.repeat(78);
let text = `THIRD-PARTY NOTICES

abl (abl.exe) and the ABL Language Server extension for VS Code include the
open-source software listed below. Each package keeps its own licence; the
licence texts follow the list. abl itself is under the MIT licence in
LICENSE.txt.

This file is generated by scripts/notices.js.

${line}
Packages
${line}

Rust crates compiled into abl.exe:
${crates.map((p) => `  ${p.name} ${p.version}  (${p.license})  ${p.url}`).join('\n')}

npm packages in the VS Code extension:
${npm.map((p) => `  ${p.name} ${p.version}  (${p.license})  ${p.url}`).join('\n')}
`;
for (const [t, pkgs] of groups) {
  const names = [...new Set(pkgs.map((p) => `${p.name} ${p.version}`))];
  text += `\n${line}\nLicence text for: ${names.join(', ')}\n${line}\n\n${t}\n`;
}
if (missing.length) {
  text += `\n${line}\nPackages without a licence file in their published source (licence as declared):\n${line}\n\n`;
  text += missing.map((p) => `  ${p.name} ${p.version}: ${p.license}  ${p.url}`).join('\n') + '\n';
}
fs.writeFileSync(out, text);
console.log(`Wrote ${path.relative(root, out)}: ${crates.length} crates, ${npm.length} npm packages, ${groups.size} licence texts, ${missing.length} without a licence file`);
