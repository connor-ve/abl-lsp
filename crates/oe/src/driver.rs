/// Compiles every `file` in the job, saving r-code into `output` when given,
/// and reports each compiler message.
pub const COMPILE: &str = r#"/* abl-driver v1: compile */
/* Generated by abl. Compiles the files listed in the job file named by the
   ABL_JOB environment variable and writes the compiler's messages to the
   result file. */
DEFINE VARIABLE cLine   AS CHARACTER NO-UNDO.
DEFINE VARIABLE cResult AS CHARACTER NO-UNDO.
DEFINE VARIABLE cOutput AS CHARACTER NO-UNDO.
DEFINE VARIABLE iSeq    AS INTEGER   NO-UNDO.
DEFINE VARIABLE i       AS INTEGER   NO-UNDO.

DEFINE TEMP-TABLE ttFile NO-UNDO
    FIELD iSeq  AS INTEGER
    FIELD cName AS CHARACTER
    INDEX ixSeq IS PRIMARY UNIQUE iSeq.

DEFINE STREAM sIn.
DEFINE STREAM sOut.

INPUT STREAM sIn FROM VALUE(OS-GETENV("ABL_JOB")).
REPEAT:
    IMPORT STREAM sIn UNFORMATTED cLine.
    CASE ENTRY(1, cLine, "~t"):
        WHEN "result" THEN cResult = ENTRY(2, cLine, "~t").
        WHEN "output" THEN cOutput = ENTRY(2, cLine, "~t").
        WHEN "file" THEN DO:
            iSeq = iSeq + 1.
            CREATE ttFile.
            ASSIGN ttFile.iSeq  = iSeq
                   ttFile.cName = ENTRY(2, cLine, "~t").
        END.
    END CASE.
END.
INPUT STREAM sIn CLOSE.

OUTPUT STREAM sOut TO VALUE(cResult).
FOR EACH ttFile BY ttFile.iSeq:
    IF cOutput = "" THEN
        COMPILE VALUE(ttFile.cName) NO-ERROR.
    ELSE
        COMPILE VALUE(ttFile.cName) SAVE INTO VALUE(cOutput) NO-ERROR.
    DO i = 1 TO COMPILER:NUM-MESSAGES:
        PUT STREAM sOut UNFORMATTED
            "msg~t" ttFile.cName
            "~t" COMPILER:GET-FILE-NAME(i)
            "~t" COMPILER:GET-ROW(i)
            "~t" COMPILER:GET-COLUMN(i)
            "~t" COMPILER:GET-NUMBER(i)
            "~t" (IF COMPILER:GET-MESSAGE-TYPE(i) = 1 THEN "error" ELSE "warning")
            "~t" REPLACE(REPLACE(COMPILER:GET-MESSAGE(i), "~n", " "), "~t", " ")
            SKIP.
    END.
    /* Problems that are not compiler messages, such as a file that can't be found. */
    IF COMPILER:NUM-MESSAGES = 0 AND ERROR-STATUS:ERROR THEN
        DO i = 1 TO ERROR-STATUS:NUM-MESSAGES:
            PUT STREAM sOut UNFORMATTED
                "msg~t" ttFile.cName "~t~t0~t0"
                "~t" ERROR-STATUS:GET-NUMBER(i)
                "~terror~t" REPLACE(ERROR-STATUS:GET-MESSAGE(i), "~t", " ")
                SKIP.
        END.
    PUT STREAM sOut UNFORMATTED
        "done~t" ttFile.cName "~t"
        (IF COMPILER:ERROR OR (COMPILER:NUM-MESSAGES = 0 AND ERROR-STATUS:ERROR) THEN "error" ELSE "ok")
        SKIP.
END.
OUTPUT STREAM sOut CLOSE.
QUIT.
"#;

/// Runs `target` and records whether it ended with an error. Errors are shown
/// with MESSAGE, which goes to standard output in batch mode.
pub const RUN: &str = r#"/* abl-driver v1: run */
/* Generated by abl. Runs the procedure named in the job file (ABL_JOB) and
   writes its outcome to the result file. -param is left for the procedure. */
DEFINE VARIABLE cLine   AS CHARACTER NO-UNDO.
DEFINE VARIABLE cResult AS CHARACTER NO-UNDO.
DEFINE VARIABLE cTarget AS CHARACTER NO-UNDO.
DEFINE VARIABLE iExit   AS INTEGER   NO-UNDO.
DEFINE VARIABLE i       AS INTEGER   NO-UNDO.

DEFINE STREAM sIn.
DEFINE STREAM sOut.

INPUT STREAM sIn FROM VALUE(OS-GETENV("ABL_JOB")).
REPEAT:
    IMPORT STREAM sIn UNFORMATTED cLine.
    CASE ENTRY(1, cLine, "~t"):
        WHEN "result" THEN cResult = ENTRY(2, cLine, "~t").
        WHEN "target" THEN cTarget = ENTRY(2, cLine, "~t").
    END CASE.
END.
INPUT STREAM sIn CLOSE.

/* 2 if a STOP condition leaves the block before the RUN returns. */
iExit = 2.
DO ON STOP UNDO, LEAVE:
    RUN VALUE(cTarget).
    iExit = 0.
    CATCH eErr AS Progress.Lang.Error:
        iExit = 1.
        DO i = 1 TO eErr:NumMessages:
            MESSAGE eErr:GetMessage(i).
        END.
        IF eErr:NumMessages = 0 AND TYPE-OF(eErr, Progress.Lang.AppError) THEN
            MESSAGE CAST(eErr, Progress.Lang.AppError):ReturnValue.
    END CATCH.
END.

OUTPUT STREAM sOut TO VALUE(cResult).
PUT STREAM sOut UNFORMATTED "exit~t" iExit SKIP.
OUTPUT STREAM sOut CLOSE.
QUIT.
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn drivers_start_with_their_marks() {
        assert!(COMPILE.starts_with(MARK_COMPILE));
        assert!(RUN.starts_with(MARK_RUN));
        assert!(LOAD_DF.starts_with(MARK_LOAD_DF));
        assert!(QUERY.starts_with(MARK_QUERY));
        assert!(IMPORT.starts_with(MARK_IMPORT));
        assert!(PROFILE.starts_with(MARK_PROFILE));
        assert!(REPL.starts_with(MARK_REPL));
        assert!(TEST.starts_with(MARK_TEST));
    }
}
