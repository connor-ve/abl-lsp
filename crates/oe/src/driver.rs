//! The ABL programs abl runs inside OpenEdge, and the files they exchange.
//!
//! abl starts `_progres -b -p <driver>.p` with the job file's path in the
//! `ABL_JOB` environment variable (so `-param` stays free for the user's
//! procedure). The job file and the result file are tab-separated lines:
//!
//! ```text
//! job:     result <TAB> <path of the result file>
//!          output <TAB> <SAVE INTO folder>        (compile; omitted for --check)
//!          file   <TAB> <name to COMPILE>          (compile; one per file)
//!          target <TAB> <procedure to RUN>         (run)
//! result:  msg  <TAB> <unit> <TAB> <file> <TAB> <row> <TAB> <col> <TAB> <number> <TAB> error|warning <TAB> <text>
//!          done <TAB> <unit> <TAB> ok|error
//!          exit <TAB> <code>                       (run)
//! ```
//!
//! The data drivers (load-df, query, import; their source is in `drivers/`) add:
//!
//! ```text
//! job:     df      <TAB> <.df file to load>          (load-df)
//!          table   <TAB> <table, maybe db-qualified> (query, import)
//!          phrase  <TAB> <WHERE / BY text>           (query)
//!          max     <TAB> <row limit, 0 for all>      (query)
//!          fields  <TAB> <comma-separated names>     (query; empty for all)
//!          out     <TAB> <data file to write>        (query)
//!          data    <TAB> <data file to read>         (import)
//!          replace <TAB> yes|no                      (import: delete all rows first)
//! result:  done  <TAB> <rows> <TAB> <more 0|1 (query) or rows deleted (import)>
//!          error <TAB> <message number or row> <TAB> <text>
//! data:    field <TAB> <name> <TAB> <type> <TAB> <extent>   (query output)
//!          field <TAB> <name> <TAB> <subscript, 0 if none>  (import input)
//!          row   <TAB> <value> <TAB> <value> ...
//! ```
//!
//! The test driver:
//!
//! ```text
//! job:     suite <TAB> <id> <TAB> cls|p <TAB> <class type name or procedure>
//!          before|after|setup|teardown <TAB> <method>   (for the suite above)
//!          test  <TAB> <method> <TAB> <case id> <TAB> <expected error type or empty>
//! result:  case  <TAB> <case id> <TAB> pass|fail|error <TAB> <ms> <TAB> <message> <TAB> <call stack>
//!          suite <TAB> <id> <TAB> <message>              (an @After failed)
//! ```
//!
//! A value is `?` for the unknown value, or `=` and the text with backslash,
//! tab, newline and carriage return written as `\\`, `\t`, `\n` and `\r`.
//! Dates are ISO 8601 and numbers use a period for the decimal point. Data
//! files are UTF-8.
//!
//! The first line of each driver names its kind, which the fake `_progres`
//! used in tests reads to know what to emulate.

